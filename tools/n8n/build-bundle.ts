// Builds tools/n8n/meeting-note.bundle.js: the meeting mapper and note writer
// from src/domain/meetings, as one script with no imports for an n8n Code
// node. `node tools/n8n/build-bundle.ts` rewrites it; a test holds it in step
// with its sources.
import { writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, bundleModules } from '../bundle-modules.ts';

export const BUNDLE_PATH = join(ROOT, 'tools', 'n8n', 'meeting-note.bundle.js');

const HEADER = `// Generated by tools/n8n/build-bundle.ts from src/domain/meetings: do not edit.
// Paste it at the top of an n8n Code node, then use dfaiMeetings.<name>
// (tools/n8n/README.md). Rebuild with: node tools/n8n/build-bundle.ts
/* eslint-disable */`;

/** The bundle's text, formatted as the repository formats code. */
export function buildBundle(): Promise<string> {
  return bundleModules({
    entry: join(ROOT, 'src', 'domain', 'meetings', 'index.ts'),
    publicNames: [
      'fromGeminiNotes',
      'meetingNote',
      'mergeMeetingNote',
      'meetingCommitMessage',
      'parseMeetingInput',
      'MeetingInputError',
    ],
    globalName: 'dfaiMeetings',
    header: HEADER,
    outPath: BUNDLE_PATH,
  });
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(BUNDLE_PATH, await buildBundle(), 'utf8');
  console.log(relative(process.cwd(), BUNDLE_PATH));
}
