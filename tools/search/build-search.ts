// Builds tools/search/search.mjs: the vault search command as one file that
// needs nothing but Node, for `.dfai-lite/search.mjs` in a vault. It is made
// from tools/search and src/domain (the app's own tag and link rules), so its
// answers agree with the app. `node tools/search/build-search.ts` rewrites it;
// a test holds it in step with its sources.
import { writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, bundleModules } from '../bundle-modules.ts';

export const SEARCH_BUNDLE_PATH = join(ROOT, 'tools', 'search', 'search.mjs');

const HEADER = `// Generated by tools/search/build-search.ts from the DFAI Lite repository: do not edit.
// Searches this vault's notes: node .dfai-lite/search.mjs --help
// The vault's index writer copies it here; rebuild with: node tools/search/build-search.ts
/* eslint-disable */`;

const FOOTER = `process.exitCode = await vaultSearch.runSearch({
  argv: process.argv.slice(2),
  scriptPath: process.argv[1] ?? '',
  cwd: process.cwd(),
  nowMs: Date.now(),
  print: (text) => process.stdout.write(text),
  printError: (text) => process.stderr.write(text),
});`;

/** The script's text, formatted as the repository formats code. */
export function buildSearchScript(): Promise<string> {
  return bundleModules({
    entry: join(ROOT, 'tools', 'search', 'search-cli.ts'),
    publicNames: ['runSearch'],
    globalName: 'vaultSearch',
    header: HEADER,
    outPath: SEARCH_BUNDLE_PATH,
    footer: FOOTER,
  });
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(SEARCH_BUNDLE_PATH, await buildSearchScript(), 'utf8');
  console.log(relative(process.cwd(), SEARCH_BUNDLE_PATH));
}
